import { compileRegistry, defaultDisplay, renderType } from './model.mjs';
import { getMessage, messages } from './messages.mjs';
import { registry } from './registry.mjs';
import { isDirectRun, outputModeFromArgv, reconcileOutputs } from './io.mjs';

function metadataRows(compiled) {
  return compiled.descriptors.map((descriptor) => ({
    id: descriptor.id,
    path: descriptor.path,
    categoryKey: descriptor.categoryKey,
    authored: {
      tsType: renderType(descriptor.authored.type, compiled),
      presence: descriptor.authored.presence,
    },
    resolved: {
      tsType: renderType(descriptor.resolved.type, compiled),
      presence: descriptor.resolved.presence,
    },
    default: descriptor.default,
    lifecycle: descriptor.lifecycle,
    impact: descriptor.impact,
    sensitivity: descriptor.sensitivity,
    key: descriptor.key ?? null,
    messages: {
      titleKey: descriptor.messages.titleKey,
      descriptionKey: descriptor.messages.descriptionKey,
      en: {
        title: getMessage(descriptor.messages.titleKey, 'en'),
        description: getMessage(descriptor.messages.descriptionKey, 'en'),
      },
      tr: {
        title: getMessage(descriptor.messages.titleKey, 'tr'),
        description: getMessage(descriptor.messages.descriptionKey, 'tr'),
      },
    },
    evidence: descriptor.evidence,
    artifacts: descriptor.artifacts,
  }));
}

function escapeTable(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function renderDocumentation(compiled, locale) {
  const title = getMessage('config.schema.title', locale);
  const warning = getMessage('config.schema.warning', locale);
  const headings = ['path', 'title', 'authored', 'resolved', 'default', 'lifecycle', 'impact', 'sensitivity']
    .map((column) => getMessage(`config.schema.column.${column}`, locale));
  const rows = compiled.descriptors.map((descriptor) => {
    const cells = [
      `\`${descriptor.path}\``,
      getMessage(descriptor.messages.titleKey, locale),
      `\`${renderType(descriptor.authored.type, compiled)}\` / ${descriptor.authored.presence}`,
      `\`${renderType(descriptor.resolved.type, compiled)}\` / ${descriptor.resolved.presence}`,
      `\`${defaultDisplay(descriptor.default)}\``,
      descriptor.lifecycle,
      descriptor.impact,
      descriptor.sensitivity,
    ];
    return `| ${cells.map(escapeTable).join(' | ')} |`;
  });
  return [
    `# ${title}`,
    '',
    `> ${warning}`,
    '',
    `${getMessage('config.schema.registry_digest', locale)}: \`${compiled.digest}\` · ${getMessage('config.schema.descriptor_count', locale)}: **${compiled.census.descriptors}**`,
    '',
    `| ${headings.join(' | ')} |`,
    `| ${headings.map(() => '---').join(' | ')} |`,
    ...rows,
    '',
    `## ${getMessage('config.schema.descriptions', locale)}`,
    '',
    ...compiled.descriptors.flatMap((descriptor) => [
      `### \`${descriptor.path}\` — ${getMessage(descriptor.messages.titleKey, locale)}`,
      '',
      getMessage(descriptor.messages.descriptionKey, locale),
      '',
    ]),
  ].join('\n');
}

export function generateMetadataAndDocumentationOutputs() {
  const compiled = compileRegistry(registry, messages);
  for (const descriptor of compiled.descriptors) {
    for (const locale of ['en', 'tr']) {
      if (!messages[locale][descriptor.categoryKey]) {
        throw new Error(`REGISTRY_CATEGORY_MESSAGE_MISSING:${locale}:${descriptor.categoryKey}`);
      }
    }
  }
  const manifest = {
    schemaVersion: 1,
    registryId: compiled.registry.registryId,
    registryDigest: compiled.digest,
    prototypeAuthority: false,
    fields: metadataRows(compiled),
  };
  const metadataJson = JSON.stringify(manifest, null, 2);
  const metadataTypeScript = [
    '/* AUTO-GENERATED by lab/descriptor-registry/generate-metadata-docs.mjs. DO NOT EDIT. */',
    '/* Prototype only: this metadata is not a production config authority. */',
    '',
    `export const CONFIG_METADATA_PROTOTYPE = ${metadataJson} as const;`,
    '',
    'export type ConfigMetadataPrototype = typeof CONFIG_METADATA_PROTOTYPE;',
  ].join('\n');
  return new Map([
    ['config-metadata.generated.json', metadataJson],
    ['config-metadata.generated.ts', metadataTypeScript],
    ['configuration-schema.en.generated.md', renderDocumentation(compiled, 'en')],
    ['configuration-schema.tr.generated.md', renderDocumentation(compiled, 'tr')],
    ['registry-census.generated.json', JSON.stringify({
      schemaVersion: 1,
      registryId: compiled.registry.registryId,
      registryDigest: compiled.digest,
      ...compiled.census,
    }, null, 2)],
  ]);
}

if (isDirectRun(import.meta.url)) {
  const result = await reconcileOutputs(generateMetadataAndDocumentationOutputs(), { mode: outputModeFromArgv(process.argv) });
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  if (result.mode === 'check' && result.changed > 0) process.exitCode = 1;
}
