import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const [binaryRoot, projectRoot, evidencePath] = process.argv.slice(2);
const api = await import(pathToFileURL(`${binaryRoot}/dist/core/file-lock.js`).href);
const { result: historical } = JSON.parse(readFileSync(evidencePath, 'utf8'));
const digest = data => createHash('sha256').update(JSON.stringify(data)).digest('hex');
const start = performance.now();
const actual = api.readRecoveredExecutionLockBoundary(projectRoot, historical.recovered.lock, historical.recovered.quarantineId);
assert.deepEqual(actual.recovered, historical.recovered);
assert.deepEqual(actual.audit, historical.audit);
assert.equal(actual.audit.action, 'recovered');
const wrong = {...historical.recovered.lock, fencingToken: {...historical.recovered.lock.fencingToken, nonce: 'f'.repeat(32)}};
assert.throws(() => api.readRecoveredExecutionLockBoundary(projectRoot, wrong, historical.recovered.quarantineId), e => e.reason === 'ownership-lost');
const {readCanonicalRunStatus} = await import(pathToFileURL(`${binaryRoot}/dist/core/run-status-authority.js`).href);
const status = readCanonicalRunStatus(projectRoot,{sprintIdHint:'sprint-762'});
assert.equal(status.active,false); assert.equal(status.lifecycle,'ABORTED'); assert.equal(status.coordinator,'absent');
console.log(JSON.stringify({utc:new Date().toISOString(),elapsedMs:performance.now()-start,auditMatch:true,quarantineMatch:true,wrongFenceRejected:true,actions:actual.lineage.map(x=>x.action),auditEventId:actual.audit.eventId,auditDigest:digest(actual.audit),lineageDigest:digest(actual.lineage),status,disposition:'HOLD — partial-effect retention not yet implemented'},null,2));
