#!/usr/bin/env node
/**
 * DESIGN-SYSTEM-001 — design-token build (design-tokens-pipeline skill kontratı).
 *
 * Tek DTCG kaynağından (design/tokens/) üç yüzey çıktısı üretir:
 *   1. src/dashboard/src/generated/theme.css        — Tailwind v4 @theme bloğu
 *      (src/dashboard/src/index.css @theme'inin BİRE-BİR aynası; parity-check ile kanıtlı)
 *   2. src/desktop/src/shared/generated/theme-tokens.gen.ts — --dk üç-katman verisi
 *      (theme-tokens.ts ile eşitlik: src/desktop/tests/theme-tokens-gen-sync.test.ts)
 *   3. src/cli/helpers/generated/palette.ts          — semantic rol → {hex, ansi256, ansi16}
 *
 * Modlar: (varsayılan) yaz + parity doğrula · `--check` drift-gate (tmp'e üret,
 * commit'li çıktılarla byte-karşılaştır; sapma = exit 1).
 */
import StyleDictionary from 'style-dictionary';
import { mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CHECK = process.argv.includes('--check');

const watchMap = JSON.parse(readFileSync(join(ROOT, 'design/tokens/watch-map.json'), 'utf8'));
const terminalMap = JSON.parse(readFileSync(join(ROOT, 'design/tokens/terminal.map.json'), 'utf8'));

const OUTPUTS = [
  { platform: 'dashboard', buildPath: join('src', 'dashboard', 'src', 'generated'), file: 'theme.css', format: 'deckent/dashboard-theme-css' },
  { platform: 'desktop', buildPath: join('src', 'desktop', 'src', 'shared', 'generated'), file: 'theme-tokens.gen.ts', format: 'deckent/desktop-gen-ts' },
  { platform: 'terminal', buildPath: join('src', 'cli', 'helpers', 'generated'), file: 'palette.ts', format: 'deckent/terminal-palette-ts' },
];

// index.css @theme sırası — üretim bu sırayla yazar ki gelecekteki import-swap
// diff'i birebir okunsun (işlevsel değil, inceleme-konforu).
const DASHBOARD_VAR_ORDER = [
  'background', 'foreground', 'card', 'cardForeground', 'popover', 'popoverForeground',
  'secondary', 'secondaryForeground', 'muted', 'mutedForeground', 'accent', 'accentForeground',
  'destructive', 'destructiveForeground', 'border', 'input',
  'primary', 'primaryForeground', 'ring',
  'brand50', 'brand100', 'brand200', 'brand300', 'brand400', 'brand500', 'brand600',
  'brand700', 'brand800', 'brand900', 'brandBg', 'brandFg',
  'gold', 'goldSoft', 'goldDeep', 'goldTint',
];

const GENERATED_HEADER =
  'AUTO-GENERATED by scripts/build-design-tokens.mjs — DO NOT EDIT.\n' +
  ' * Kaynak: design/tokens/ (DTCG). Değişiklik = kaynakta + `npm run build:tokens`.\n' +
  ' * Wiring: DESIGN-SYSTEM-001 slice 2 (bu dosya henüz tüketilmiyorsa bile drift-gate altındadır).';

const kebab = (s) => s.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/([a-zA-Z])(\d)/g, '$1-$2').toLowerCase();
const fontStack = (arr) => arr.map((f) => (/^[a-zA-Z0-9-]+$/.test(f) ? f : `"${f}"`)).join(', ');
const tsKey = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : `'${k}'`);

function tokenValueMap(dictionary) {
  const map = new Map();
  for (const t of dictionary.allTokens) map.set(t.path.join('.'), t.$value ?? t.value);
  return map;
}

// ── xterm-256 en-yakın renk (kademe-dürüst degrade) ─────────────────────────
const CUBE_LEVELS = [0, 95, 135, 175, 215, 255];
function hexToRgb(hex) {
  return [parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16)];
}
function nearestAnsi256(hex) {
  const [r, g, b] = hexToRgb(hex);
  let best = { idx: 16, dist: Infinity };
  const consider = (idx, cr, cg, cb) => {
    const dist = (r - cr) ** 2 + (g - cg) ** 2 + (b - cb) ** 2;
    if (dist < best.dist) best = { idx, dist };
  };
  for (let ri = 0; ri < 6; ri++)
    for (let gi = 0; gi < 6; gi++)
      for (let bi = 0; bi < 6; bi++)
        consider(16 + 36 * ri + 6 * gi + bi, CUBE_LEVELS[ri], CUBE_LEVELS[gi], CUBE_LEVELS[bi]);
  for (let i = 0; i < 24; i++) {
    const v = 8 + 10 * i;
    consider(232 + i, v, v, v);
  }
  return best.idx;
}

// ── Formatlar ────────────────────────────────────────────────────────────────
function dashboardThemeCss({ dictionary }) {
  const map = tokenValueMap(dictionary);
  const lines = DASHBOARD_VAR_ORDER.map((name) => {
    const value = map.get(`dashboard.${name}`);
    if (value === undefined) throw new Error(`dashboard token missing: ${name}`);
    return `  --color-${kebab(name)}: ${value};`;
  });
  lines.push(
    `  --font-sans: ${fontStack(map.get('font.body'))};`,
    `  --font-mono: ${fontStack(map.get('font.dashboardMono'))};`,
    `  --radius: ${map.get('radius.control')};`,
  );
  return `/* ${GENERATED_HEADER.replace(/\n \* /g, '\n   ')} */\n@theme {\n${lines.join('\n')}\n}\n`;
}

function desktopGenTs({ dictionary }) {
  const chart = dictionary.allTokens.filter((t) => t.path[0] === 'color' && t.path[1] === 'chart');
  const primitives = chart.map((t) => `  ${tsKey(t.path[2])}: '${t.$value ?? t.value}',`).join('\n');
  const watches = Object.entries(watchMap.watches)
    .map(([watch, roles]) => {
      const body = Object.entries(roles).map(([role, prim]) => `    ${tsKey(role)}: '${prim}',`).join('\n');
      return `  ${tsKey(watch)}: {\n${body}\n  },`;
    })
    .join('\n');
  const components = Object.entries(watchMap.componentTokens)
    .map(([c, s]) => `  ${tsKey(c)}: '${s}',`)
    .join('\n');
  return `/**\n * ${GENERATED_HEADER}\n * Eşitlik-kilidi: src/desktop/tests/theme-tokens-gen-sync.test.ts\n */\nexport const GEN_PRIMITIVES = {\n${primitives}\n} as const;\n\nexport const GEN_WATCHES = {\n${watches}\n} as const;\n\nexport const GEN_COMPONENT_TOKENS = {\n${components}\n} as const;\n`;
}

function terminalPaletteTs({ dictionary }) {
  const map = tokenValueMap(dictionary);
  const roleNames = Object.keys(terminalMap.roles);
  const entries = roleNames
    .map((role) => {
      const { primitive, ansi16 } = terminalMap.roles[role];
      const hex = map.get(`color.chart.${primitive}`);
      if (hex === undefined) throw new Error(`terminal role "${role}" points at unknown primitive "${primitive}"`);
      return `  ${role}: { hex: '${hex}', ansi256: ${nearestAnsi256(hex)}, ansi16: '${ansi16}' },`;
    })
    .join('\n');
  return (
    `/**\n * ${GENERATED_HEADER}\n * Kapılar (NO_COLOR/FORCE_COLOR/TTY) src/cli/helpers/theme.ts'te kalır;\n * bu dosya yalnız rol→renk verisidir (DT-5 kod-ayağı).\n */\n` +
    `export type PaletteRole = ${roleNames.map((r) => `'${r}'`).join(' | ')};\n\n` +
    `export interface PaletteEntry {\n  /** Truecolor kademesi (NOVA token değeri). */\n  hex: string;\n  /** En yakın xterm-256 indeksi (build-time hesap). */\n  ansi256: number;\n  /** Bugünkü 16-renk SGR kodu — davranış-koruyucu fallback. */\n  ansi16: string;\n}\n\n` +
    `export const PALETTE: Record<PaletteRole, PaletteEntry> = {\n${entries}\n};\n`
  );
}

// ── Dashboard parity-check (index.css @theme ↔ üretilen theme.css) ──────────
function parseThemeBlock(css, label) {
  const start = css.indexOf('@theme');
  if (start === -1) throw new Error(`${label}: @theme bloğu bulunamadı`);
  const open = css.indexOf('{', start);
  const close = css.indexOf('}', open);
  const vars = new Map();
  for (const m of css.slice(open + 1, close).matchAll(/--([A-Za-z0-9-]+)\s*:\s*([^;]+);/g)) {
    vars.set(m[1], m[2].replace(/\s+/g, ' ').trim().toLowerCase());
  }
  return vars;
}

function dashboardParity(generatedCss) {
  const indexCss = readFileSync(join(ROOT, 'src', 'dashboard', 'src', 'index.css'), 'utf8');
  const expected = parseThemeBlock(indexCss, 'index.css');
  const actual = parseThemeBlock(generatedCss, 'theme.css');
  const problems = [];
  for (const [name, value] of expected) {
    if (!actual.has(name)) problems.push(`eksik: --${name}`);
    else if (actual.get(name) !== value) problems.push(`fark: --${name} beklenen "${value}" üretilen "${actual.get(name)}"`);
  }
  for (const name of actual.keys()) if (!expected.has(name)) problems.push(`fazla: --${name}`);
  return problems;
}

// ── Kart parity: foundations + components (design-critic 2026-07-31 #3) ────
// Kartlardaki her renk-literal'i token kümesinin üyesi olmak zorunda; ayrıca
// colors.html'in PRIM sözlüğü chart primitives ile bire-bir kalmalı. Token
// değişince kartlar sessiz bayatlayamaz — build kırmızıya döner.
const FOUNDATION_CARDS = ['typography.html', 'colors.html', 'spacing.html', 'motion.html'];
function componentCardPaths() {
  const base = join(ROOT, 'design', 'claude-design', 'components');
  try {
    return readdirSync(base)
      .map((d) => join(base, d, 'index.html'))
      .filter((p) => {
        try { readFileSync(p); return true; } catch { return false; }
      });
  } catch {
    return [];
  }
}
function foundationsParity() {
  const problems = [];
  const prim = JSON.parse(readFileSync(join(ROOT, 'design', 'tokens', 'primitives.tokens.json'), 'utf8'));
  const allowed = new Set();
  (function collect(node) {
    for (const [key, value] of Object.entries(node)) {
      if (key.startsWith('$') || value === null || typeof value !== 'object') continue;
      if (typeof value.$value === 'string' && value.$value.startsWith('#')) allowed.add(value.$value.toLowerCase());
      else collect(value);
    }
  })(prim);
  const allowedTriplets = new Set([...allowed].map((h) => hexToRgb(h).join(',')));
  const cardPaths = [
    ...FOUNDATION_CARDS.map((c) => ({ label: c, path: join(ROOT, 'design', 'claude-design', 'foundations', c) })),
    ...componentCardPaths().map((p) => ({ label: p.split('claude-design')[1] ?? p, path: p })),
  ];
  for (const { label: card, path } of cardPaths) {
    let html;
    try {
      html = readFileSync(path, 'utf8');
    } catch {
      problems.push(`${card}: dosya yok`);
      continue;
    }
    // Tipli muafiyet: kart, temsilî (token-olmayan ama marka-iddiası taşımayan)
    // hex'leri AÇIKÇA beyan edebilir: <!-- @parity-allow #AABBCC #DDEEFF (gerekçe) -->
    // Beyansız token-dışı hex yine kırmızıdır — sessiz istisna yok.
    const cardAllow = new Set(
      [...html.matchAll(/@parity-allow\s+([^>]*?)(?:\(|-->)/g)]
        .flatMap((m) => m[1].match(/#[0-9a-fA-F]{6}\b/g) ?? [])
        .map((h) => h.toLowerCase()),
    );
    for (const m of html.matchAll(/#[0-9a-fA-F]{3,6}\b/g)) {
      const hex = m[0].toLowerCase();
      if (hex.length !== 7) problems.push(`${card}: kısa/geçersiz hex "${m[0]}"`);
      else if (!allowed.has(hex) && !cardAllow.has(hex)) problems.push(`${card}: token-dışı hex "${m[0]}"`);
    }
    for (const m of html.matchAll(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/g)) {
      if (!allowedTriplets.has(`${m[1]},${m[2]},${m[3]}`)) problems.push(`${card}: token-dışı rgb(${m[1]},${m[2]},${m[3]})`);
    }
  }
  try {
    const colorsHtml = readFileSync(join(ROOT, 'design', 'claude-design', 'foundations', 'colors.html'), 'utf8');
    for (const [name, def] of Object.entries(prim.color.chart)) {
      if (name.startsWith('$')) continue;
      if (!new RegExp(`${name}\\s*:\\s*'${def.$value}'`).test(colorsHtml)) {
        problems.push(`colors.html PRIM: ${name}='${def.$value}' bulunamadı (kart bayat)`);
      }
    }
  } catch {
    /* colors.html yokluğu yukarıda raporlandı */
  }
  return problems;
}

// ── Koşum ───────────────────────────────────────────────────────────────────
const outRoot = CHECK ? mkdtempSync(join(tmpdir(), 'deckent-tokens-')) : ROOT;
try {
  const sd = new StyleDictionary({
    source: [join(ROOT, 'design', 'tokens', '*.tokens.json')],
    log: { verbosity: 'silent' },
    hooks: {
      formats: {
        'deckent/dashboard-theme-css': dashboardThemeCss,
        'deckent/desktop-gen-ts': desktopGenTs,
        'deckent/terminal-palette-ts': terminalPaletteTs,
      },
    },
    platforms: Object.fromEntries(
      OUTPUTS.map((o) => [
        o.platform,
        { buildPath: join(outRoot, o.buildPath) + sep, files: [{ destination: o.file, format: o.format }] },
      ]),
    ),
  });
  await sd.buildAllPlatforms();

  const failures = [];

  const parityProblems = dashboardParity(readFileSync(join(outRoot, OUTPUTS[0].buildPath, OUTPUTS[0].file), 'utf8'));
  if (parityProblems.length > 0) failures.push(`dashboard parity: ${parityProblems.join(' | ')}`);

  const foundationProblems = foundationsParity();
  if (foundationProblems.length > 0) failures.push(`foundations parity: ${foundationProblems.join(' | ')}`);

  if (CHECK) {
    for (const o of OUTPUTS) {
      const committedPath = join(ROOT, o.buildPath, o.file);
      let committed = null;
      try {
        committed = readFileSync(committedPath, 'utf8');
      } catch {
        failures.push(`drift: ${join(o.buildPath, o.file)} commit'li kopya yok — \`npm run build:tokens\` çalıştır`);
        continue;
      }
      const fresh = readFileSync(join(outRoot, o.buildPath, o.file), 'utf8');
      if (committed !== fresh) failures.push(`drift: ${join(o.buildPath, o.file)} kaynaktan sapmış — \`npm run build:tokens\` çalıştır`);
    }
  }

  if (failures.length > 0) {
    for (const f of failures) console.error(`[design-tokens] ✗ ${f}`);
    process.exit(1);
  }
  console.log(
    `[design-tokens] OK — ${OUTPUTS.map((o) => o.file).join(', ')} ${CHECK ? 'in-sync' : 'üretildi'}; dashboard @theme + foundations parity doğrulandı.`,
  );
} finally {
  if (CHECK) rmSync(outRoot, { recursive: true, force: true });
}
